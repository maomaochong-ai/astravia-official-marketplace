#!/usr/bin/env node
// Stages the Excalidraw web app into abilities/plugins/excalidraw/web/.
//
// The site is not committed: the repository archive limit forbids it. Instead
// `payload/manifest.json` pins one upstream commit, and this recipe fetches that
// exact tree, builds `excalidraw-app` with upstream's own Vite config, and copies
// the result into the plugin package.
//
// Nothing here reimplements the editor. The only build-time change is a wrapper
// config (generated below) that drops the three plugins which exist for the
// excalidraw.com deployment — service worker, sitemap, type/lint overlay — and
// switches asset URLs to relative paths. The application source is untouched.
//
// Usage:
//   node scripts/build-excalidraw-web.mjs --slug excalidraw [--if-missing] [--source <prepared-tree>]
import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const option = name => {
  const index = process.argv.indexOf(name);
  return index < 0 ? undefined : process.argv[index + 1];
};
const log = message => console.log(`[excalidraw-web] ${message}`);

// Plugins that only make sense for a public deployment of excalidraw.com.
const DROPPED_PLUGINS = ['vite-plugin-pwa', 'vite-plugin-sitemap', 'vite-plugin-checker'];

const BUILD_CONFIG = `// Generated by scripts/build-excalidraw-web.mjs — do not edit in place.
import upstream from "./vite.config.mts";

const DROPPED = ${JSON.stringify(DROPPED_PLUGINS)};
const isDropped = (name) =>
  typeof name === "string" && DROPPED.some((prefix) => name.startsWith(prefix));

export default async (env) => {
  const config =
    typeof upstream === "function" ? await upstream(env) : await upstream;

  const plugins = [];
  for (const plugin of (config.plugins ?? []).flat(Infinity)) {
    const resolved =
      plugin && typeof plugin.then === "function" ? await plugin : plugin;
    if (!resolved || isDropped(resolved.name)) {
      continue;
    }
    plugins.push(resolved);
  }

  const stub = new URL("./pwa-register-stub.ts", import.meta.url).pathname;
  const legacyFs = new URL("./browser-fs-access-legacy.ts", import.meta.url).pathname;
  const resolveConfig = config.resolve ?? {};
  const aliases = Array.isArray(resolveConfig.alias)
    ? resolveConfig.alias
    : Object.entries(resolveConfig.alias ?? {}).map(([find, replacement]) => ({
        find,
        replacement,
      }));

  return {
    ...config,
    base: "./",
    resolve: {
      ...resolveConfig,
      alias: [
        ...aliases,
        { find: /^virtual:pwa-register$/, replacement: stub },
        { find: /^browser-fs-access$/, replacement: legacyFs },
      ],
    },
    build: { ...config.build, sourcemap: false },
    plugins,
  };
};
`;

const PWA_STUB = `// Generated by scripts/build-excalidraw-web.mjs — stands in for the
// \`virtual:pwa-register\` module that vite-plugin-pwa would provide. A packaged
// site has no service worker, so registration is a no-op.
export const registerSW = () => () => {};
export let updateSW = () => {};
export default registerSW;
`;

const LEGACY_FS_STUB = `// Generated by scripts/build-excalidraw-web.mjs — the packaged site cannot use the
// native file pickers (a frame cannot open them), so the anchor download and the
// hidden file input are the only paths that reach the host bridge.
export {
  fileOpenLegacy as fileOpen,
  fileSaveLegacy as fileSave,
} from "__MODULE__";
export const supported = false;
`;

// The package declares no subpath export for its dist file, so the shim points at it
// with a relative path computed once the working directory is known.
function legacyFsStub(sourceDir, appDir) {
  const dist = join(sourceDir, 'node_modules/browser-fs-access/dist/index.modern.js');
  if (!existsSync(dist)) {
    fail(`browser-fs-access is not installed at ${dist}`);
  }
  const specifier = relative(appDir, dist).split(sep).join('/');
  return LEGACY_FS_STUB.replace('__MODULE__', specifier.startsWith('.') ? specifier : `./${specifier}`);
}

function fail(message) {
  console.error(`[excalidraw-web] ${message}`);
  process.exit(1);
}

const slug = option('--slug') ?? fail('pass --slug <plugin-slug>');
const ifMissing = process.argv.includes('--if-missing');
const sourceOverride = option('--source');

const pluginDir = join(root, 'abilities/plugins', slug);
const pinPath = join(pluginDir, 'payload/manifest.json');
if (!existsSync(pinPath)) {
  fail(`no payload/manifest.json in ${pluginDir}`);
}
const pin = JSON.parse(readFileSync(pinPath, 'utf8'));
const { build } = pin;
if (build?.kind !== 'source-build') {
  fail(`expected build.kind "source-build", found ${JSON.stringify(build?.kind)}`);
}
if (!/^[a-f0-9]{40}$/.test(build.commit ?? '')) {
  fail('build.commit must be a full 40-character upstream commit');
}

const siteDir = join(pluginDir, pin.site ?? 'web');
const markerPath = join(siteDir, '.build.json');
const recipeVersion = build.recipeVersion ?? 1;

if (ifMissing && existsSync(markerPath) && existsSync(join(siteDir, 'index.html'))) {
  const marker = JSON.parse(readFileSync(markerPath, 'utf8'));
  if (marker.commit === build.commit && marker.recipeVersion === recipeVersion) {
    log(`site already built from ${build.commit.slice(0, 7)} — nothing to do`);
    process.exit(0);
  }
}

// ---------------------------------------------------------------- source tree
const cacheDir = process.env.EXCALIDRAW_WEB_CACHE
  ? resolve(process.env.EXCALIDRAW_WEB_CACHE)
  : join(root, '.cache/excalidraw-web');
const sourceDir = sourceOverride
  ? resolve(sourceOverride)
  : join(cacheDir, `src-${build.commit.slice(0, 12)}`);

function download(url, target) {
  log(`fetching ${url}`);
  mkdirSync(dirname(target), { recursive: true });
  execFileSync('curl', ['-sSL', '--fail', '--retry', '3', '--retry-delay', '5', '-o', target, url], { stdio: 'inherit' });
}

if (!existsSync(join(sourceDir, 'excalidraw-app/vite.config.mts'))) {
  if (sourceOverride) {
    fail(`--source ${sourceDir} does not look like the excalidraw repository`);
  }
  const archive = join(cacheDir, `${build.commit}.tar.gz`);
  if (!existsSync(archive)) {
    download(`${build.upstream.replace(/\/$/, '')}/archive/${build.commit}.tar.gz`, archive);
  }
  log(`extracting into ${sourceDir}`);
  rmSync(sourceDir, { recursive: true, force: true });
  mkdirSync(sourceDir, { recursive: true });
  execFileSync('tar', ['-xzf', archive, '-C', sourceDir, '--strip-components=1'], { stdio: 'inherit' });
}

const appDir = join(sourceDir, build.package ?? 'excalidraw-app');
if (!existsSync(join(appDir, 'vite.config.mts'))) {
  fail(`upstream tree has no ${build.package ?? 'excalidraw-app'}/vite.config.mts`);
}

// ------------------------------------------------------------------ toolchain
if (!existsSync(join(sourceDir, 'node_modules/vite/package.json'))) {
  log('installing upstream dependencies (yarn classic, frozen lockfile)');
  execFileSync(
    'npx',
    ['-y', 'yarn@1.22.22', 'install', '--frozen-lockfile', '--ignore-engines', '--non-interactive', '--ignore-scripts'],
    { cwd: sourceDir, stdio: 'inherit', env: { ...process.env, YARN_CACHE_FOLDER: join(cacheDir, 'yarn-cache') } },
  );
}

writeFileSync(join(appDir, 'vite.astravia.config.mts'), BUILD_CONFIG);
writeFileSync(join(appDir, 'pwa-register-stub.ts'), PWA_STUB);
writeFileSync(join(appDir, 'browser-fs-access-legacy.ts'), legacyFsStub(sourceDir, appDir));

// ---------------------------------------------------------------------- build
log('building the site');
const viteBin = join(sourceDir, 'node_modules/.bin/vite');
rmSync(join(appDir, 'build'), { recursive: true, force: true });
execFileSync(existsSync(viteBin) ? viteBin : 'npx', existsSync(viteBin) ? ['build', '--config', 'vite.astravia.config.mts'] : ['-y', 'vite', 'build', '--config', 'vite.astravia.config.mts'], {
  cwd: appDir,
  stdio: 'inherit',
  env: {
    ...process.env,
    VITE_APP_DISABLE_SENTRY: 'true',
    VITE_APP_ENABLE_ESLINT: 'false',
    NODE_OPTIONS: `${process.env.NODE_OPTIONS ?? ''} --max-old-space-size=4096`.trim(),
  },
});

const builtDir = join(appDir, 'build');
if (!existsSync(join(builtDir, 'index.html'))) {
  fail('build produced no index.html');
}

// ------------------------------------------------------------------ post-pass
// Everything below adapts a deployment bundle into a self-contained folder. The
// application code itself is never touched: only the emitted HTML/CSS shell.
const CDN = 'https://excalidraw.nyc3.cdn.digitaloceanspaces.com/oss/';

function postprocessIndexHtml(html) {
  let out = html;

  // Upstream points fonts at its CDN with a root-absolute fallback. Inside a
  // package neither exists, so the base the document was loaded from wins.
  const assetPath = /window\.EXCALIDRAW_ASSET_PATH\s*=\s*\[[\s\S]*?\];/;
  if (!assetPath.test(out)) {
    fail('index.html no longer sets EXCALIDRAW_ASSET_PATH as an array — update this recipe');
  }
  out = out.replace(assetPath, 'window.EXCALIDRAW_ASSET_PATH = document.baseURI;');

  // Preloads that would hit the CDN before the local copy is even considered.
  out = out.replace(new RegExp(`<link[^>]+href="${CDN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[^>]*>`, 'g'), '');

  // The pageview beacon: an outbound request from a package that must run
  // offline, and its iframe branch calls an undefined `action`. Dropped whole —
  // the guard below fails the build if upstream renames it.
  const analytics = /<script>\/\/[^<]*simpleanalyticscdn[\s\S]*?<\/script>/;
  if (!analytics.test(out)) {
    fail('index.html no longer carries the Simple Analytics loader — update this recipe');
  }
  out = out.replace(analytics, '');

  return out;
}

function postprocessCss(css) {
  // The UI font is declared with a CDN URL and a relative fallback. Keep only
  // the bundled copy, which sits next to the emitted stylesheet's parent.
  let out = css.replace(
    new RegExp(`url\\(${CDN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[^)]*\\)\\s*format\\("woff2"\\),\\s*`, 'g'),
    '',
  );
  // `./Assistant-*.woff2` is emitted at the site root, not next to the CSS in assets/.
  out = out.replace(/url\(\.\/Assistant-/g, 'url(../Assistant-');
  return out;
}

log(`staging into ${siteDir}`);
rmSync(siteDir, { recursive: true, force: true });
cpSync(builtDir, siteDir, { recursive: true });

for (const entry of readdirSync(siteDir)) {
  if (entry === '_headers' || entry === 'sw.js' || entry === 'manifest.webmanifest' || /^workbox-.*\.js$/.test(entry)) {
    rmSync(join(siteDir, entry), { recursive: true, force: true });
  }
}

writeFileSync(join(siteDir, 'index.html'), postprocessIndexHtml(readFileSync(join(siteDir, 'index.html'), 'utf8')));

const assetsDir = join(siteDir, 'assets');
for (const entry of readdirSync(assetsDir)) {
  if (!entry.endsWith('.css')) {
    continue;
  }
  const cssPath = join(assetsDir, entry);
  writeFileSync(cssPath, postprocessCss(readFileSync(cssPath, 'utf8')));
}

writeFileSync(
  markerPath,
  `${JSON.stringify({ commit: build.commit, recipeVersion, upstream: build.upstream, builtBy: 'scripts/build-excalidraw-web.mjs' }, null, 2)}\n`,
);

// ------------------------------------------------------------------ verification
function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) {
      out.push(...walk(path));
    } else {
      out.push(path);
    }
  }
  return out;
}

const problems = [];
const indexHtml = readFileSync(join(siteDir, 'index.html'), 'utf8');

if (/(?:src|href)="\/[^/]/.test(indexHtml)) {
  problems.push('index.html still references a root-absolute asset');
}
if (!/window\.EXCALIDRAW_ASSET_PATH = document\.baseURI;/.test(indexHtml)) {
  problems.push('index.html does not bind the asset path to the document base');
}
if (/127\.0\.0\.1|localhost/.test(indexHtml)) {
  problems.push('index.html contains a development host');
}
if (indexHtml.includes(CDN)) {
  problems.push('index.html still preloads from the upstream CDN');
}
if (indexHtml.includes('simpleanalyticscdn')) {
  problems.push('index.html still loads the pageview beacon');
}

for (const cssFile of walk(assetsDir).filter(file => file.endsWith('.css'))) {
  if (readFileSync(cssFile, 'utf8').includes(CDN)) {
    problems.push(`${cssFile.slice(siteDir.length + 1)} still references the upstream CDN`);
  }
}

// Every font the application asks for at runtime must exist next to the site.
const scripts = readdirSync(assetsDir).filter(entry => entry.endsWith('.js'));
if (!scripts.length) {
  problems.push('no scripts in assets/');
}
const referenced = new Set();
for (const script of scripts) {
  const js = readFileSync(join(assetsDir, script), 'utf8');
  for (const font of js.match(/fonts\/[A-Za-z]+\/[A-Za-z0-9._-]+\.woff2/g) ?? []) {
    referenced.add(font);
  }
}
if (!referenced.size) {
  problems.push('no font references found — the hand-drawn faces would silently fall back');
}
for (const font of referenced) {
  if (!existsSync(join(siteDir, font))) {
    problems.push(`missing font asset ${font}`);
  }
}
log(`${referenced.size} bundled fonts referenced by the app`);

// The package ceiling is 100 MB unpacked; warn well before that.
let total = 0;
for (const file of walk(siteDir)) {
  total += statSync(file).size;
}
log(`site size ${(total / 1024 / 1024).toFixed(1)} MB`);

if (problems.length) {
  fail(`site verification failed:\n  - ${problems.join('\n  - ')}`);
}

log(`done — ${build.commit.slice(0, 7)} staged into ${siteDir.slice(root.length + 1)}`);
