/**
 * 「空壳」端到端验证：从**已发布的 .astraviapkg** 出发，按 plugin.json 声明的制品
 * 物化 dbx-engine 服务，再走真实 HTTP 链路验证「API 接入」能不能拿到数据、能不能查。
 *
 * 与 harness/api-data-access-e2e.mjs 的区别：那个直接 import server/src/http-server.mjs
 * （源码），本脚本跑的是**宿主真正装出来的那一份**——包内 dist 内联的 bridge（server/main.mjs）
 * 加上按平台下载/内置的 dbx-mcp 二进制，都以 plugin.json 钉住的 sha256 校验。
 *
 * 用法：
 *   node harness/api-data-access-shell-e2e.mjs
 *   node harness/api-data-access-shell-e2e.mjs --bridge <main.mjs>   # 用候选 bridge 覆盖包内的
 *   node harness/api-data-access-shell-e2e.mjs --pkg <x.astraviapkg> --keep
 *
 * `/query` 需要引擎的 DuckDB 驱动；不设 `DBX_DUCKDB_DRIVER_PATH` 时 `/query` 会返回 501
 * （接口数据已取到，只是没地方跑 SQL），属环境缺失而非功能回归。
 * 环境变量：MOCK_PORT / MOCK_TOKEN 与 harness/api-data-access-mock-api.mjs 保持一致。
 */
import { execFileSync, spawn } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createServer } from "node:net";
import { tmpdir } from "node:os";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const argv = process.argv.slice(2);
const flag = (name) => argv.includes(`--${name}`);
const valueOf = (name, fallback = null) => {
	const index = argv.indexOf(`--${name}`);
	return index >= 0 ? argv[index + 1] : fallback;
};

const KEEP = flag("keep");
const MOCK_PORT = Number(process.env.MOCK_PORT ?? 8787);
const MOCK_TOKEN = process.env.MOCK_TOKEN ?? "secret-token-123";
const MOCK_URL = `http://127.0.0.1:${MOCK_PORT}/api/v1/posts`;

const results = [];
function check(label, ok, detail) {
	results.push({ label, ok });
	console.log(`${ok ? "PASS" : "FAIL"}  ${label}${detail ? ` — ${detail}` : ""}`);
}
const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

/** 当前平台 → plugin.json 用的平台标签（与 src/shared/platform.ts 一致）。 */
function platformTag() {
	if (process.platform === "darwin") return process.arch === "arm64" ? "darwin-arm64" : "darwin-x64";
	if (process.platform === "win32") return "win32-x64";
	return null;
}

/** 解出 vite `?raw` 内联进 dist 的模板字符串（`...`），按 JS 模板字面量规则反转义。 */
function unescapeTemplate(raw) {
	let out = "";
	for (let i = 0; i < raw.length; i += 1) {
		const ch = raw[i];
		if (ch !== "\\") {
			out += ch;
			continue;
		}
		const next = raw[i += 1];
		if (next === "n") out += "\n";
		else if (next === "r") out += "\r";
		else if (next === "t") out += "\t";
		else if (next === "0") out += "\0";
		else if (next === "x") { out += String.fromCharCode(Number.parseInt(raw.slice(i + 1, i + 3), 16)); i += 2; }
		else if (next === "u") { out += String.fromCharCode(Number.parseInt(raw.slice(i + 1, i + 5), 16)); i += 4; }
		else out += next;
	}
	return out;
}

/** 从包里 dist 的产物中抠出内联的 server/main.mjs（宿主 activation 里 base64 的那份）。 */
function extractInlinedBridge(distDir) {
	for (const entry of readdirSync(distDir)) {
		if (!entry.endsWith(".js")) continue;
		const src = readFileSync(join(distDir, entry), "utf8");
		const marker = src.indexOf("dbx-pro engine bundle - generated by scripts/build-engine.mjs");
		if (marker < 0) continue;
		const start = src.lastIndexOf("`", marker);
		if (start < 0) continue;
		let end = -1;
		for (let i = start + 1; i < src.length; i += 1) {
			if (src[i] === "\\") { i += 1; continue; }
			if (src[i] === "`") { end = i; break; }
		}
		if (end < 0) continue;
		return { bundle: entry, text: unescapeTemplate(src.slice(start + 1, end)) };
	}
	return null;
}

/** 拿一个空闲端口（先绑 0 再放开；宿主给的是 ASTRAVIA_SERVICE_PORT，等价做法）。 */
function freePort() {
	return new Promise((ok) => {
		const probe = createServer();
		probe.listen(0, "127.0.0.1", () => {
			const { port } = probe.address();
			probe.close(() => ok(port));
		});
	});
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function waitFor(label, probe, timeoutMs) {
	const deadline = Date.now() + timeoutMs;
	while (Date.now() < deadline) {
		try {
			if (await probe()) return true;
		} catch {
			/* 还没起来 */
		}
		await sleep(200);
	}
	console.log(`      （等待 ${label} 超时 ${timeoutMs}ms）`);
	return false;
}

// ---------------------------------------------------------------- 1) 取出安装包
const pkgPath = resolve(
	REPO,
	valueOf("pkg") ??
		(() => {
			const dir = join(REPO, "release");
			const found = readdirSync(dir).filter((f) => f.endsWith(".astraviapkg")).sort();
			if (found.length === 0) throw new Error("release/ 下没有 .astraviapkg");
			return join("release", found[found.length - 1]);
		})(),
);
const work = mkdtempSync(join(tmpdir(), "api-shell-e2e-"));
const pkgDir = join(work, "pkg");
execFileSync("unzip", ["-q", pkgPath, "-d", pkgDir]);
const manifest = JSON.parse(readFileSync(join(pkgDir, "plugin.json"), "utf8"));
console.log(`安装包: ${pkgPath}  (${basename(pkgPath)})`);
console.log(`解压到: ${pkgDir}\n`);

// ---------------------------------------------------------------- 2) 按声明物化服务
const tag = platformTag();
check("当前平台在 plugin.json 里有对应制品", Boolean(tag), `platform=${process.platform}-${process.arch}`);

const service = (manifest.providers?.services ?? []).find((s) => s.id === "dbx-engine");
check("plugin.json 声明了 dbx-engine 服务", Boolean(service), service ? `runtime=${service.runtime?.kind}@${service.runtime?.version}` : "");
const declaredPlatform = service?.runtime?.platforms?.[tag] ?? null;
const artifacts = declaredPlatform?.artifacts ?? [];
const declaredBridge = artifacts.find((a) => a.destination === "server/main.mjs");
const declaredBin = artifacts.find((a) => a.destination?.startsWith("server/bin/"));
check("制品清单含 server/main.mjs 与平台二进制", Boolean(declaredBridge && declaredBin), artifacts.map((a) => a.destination).join(", "));
console.log(`      服务启动参数（照抄声明）: ${JSON.stringify(service?.process?.args)}｜health=${service?.health?.path} timeoutMs=${service?.health?.timeoutMs}`);

const inlined = extractInlinedBridge(join(pkgDir, "dist"));
const bridgeOverride = valueOf("bridge");
const bridgeBytes = bridgeOverride
	? readFileSync(resolve(bridgeOverride))
	: Buffer.from(inlined?.text ?? readFileSync(join(REPO, "server/main.mjs")));
const bridgeSha = sha256(bridgeBytes);
console.log(
	`      bridge 来源: ${bridgeOverride ? `--bridge ${bridgeOverride}` : `包内 ${inlined?.bundle} 内联`}｜${bridgeBytes.length} bytes｜sha256=${bridgeSha.slice(0, 16)}…`,
);
check(
	"bridge 字节与 plugin.json 钉住的 sha256 一致（宿主 install 会校验）",
	bridgeSha === declaredBridge?.sha256,
	`declared=${String(declaredBridge?.sha256).slice(0, 16)}… actual=${bridgeSha.slice(0, 16)}…`,
);

const binName = declaredBin?.destination?.split("/").pop();
const assetsDir = join(pkgDir, "dist", "assets");
const bundledBin = readdirSync(assetsDir).find((f) => f.startsWith(binName));
const binBytes = readFileSync(join(assetsDir, bundledBin));
check(
	`平台二进制 ${binName} 随包分发且 sha256 一致`,
	sha256(binBytes) === declaredBin?.sha256,
	`${bundledBin}｜${(binBytes.length / 1_048_576).toFixed(1)}MB`,
);

const runtimeDir = join(work, "runtime");
const dataDir = join(work, "data");
mkdirSync(join(runtimeDir, "server", "bin"), { recursive: true });
mkdirSync(dataDir, { recursive: true });
// 宿主的 runtime 目录只 stage 本产物与 dbx-mcp 二进制，这里照抄同样的布局。
writeFileSync(join(runtimeDir, "server", "main.mjs"), bridgeBytes);
writeFileSync(join(runtimeDir, "server", "bin", binName), binBytes, { mode: 0o755 });
console.log(`      runtime: ${join(runtimeDir, "server")}\n`);

// ---------------------------------------------------------------- 3) 起服务（照宿主的方式）
const port = await freePort();
const base = `http://127.0.0.1:${port}`;
// 宿主按 plugin.json 的 process.args 拼命令行，这里逐字照做（只替换两个占位符）。
const declaredArgs = service?.process?.args ?? ["--port", "${ASTRAVIA_SERVICE_PORT}", "--data", "${ASTRAVIA_SERVICE_DATA_DIR}", "--auth-disabled"];
const serviceArgs = declaredArgs.map((arg) =>
	arg
		.replace("${ASTRAVIA_SERVICE_PORT}", String(port))
		.replace("${ASTRAVIA_SERVICE_DATA_DIR}", dataDir),
);
const child = spawn(process.execPath, [join(runtimeDir, "server", "main.mjs"), ...serviceArgs], {
	stdio: ["ignore", "pipe", "pipe"],
});
let childLog = "";
child.stdout.on("data", (c) => { childLog += c; });
child.stderr.on("data", (c) => { childLog += c; });

const healthy = await waitFor("dbx-engine /health", async () => {
	const res = await fetch(`${base}/health`);
	return res.ok;
}, 30_000);
check("dbx-engine 起来并通过 /health（宿主 timeoutMs=30000）", healthy, base);
if (!healthy) {
	console.log(`      服务输出：\n${childLog.slice(0, 800)}`);
	child.kill("SIGKILL");
	process.exit(1);
}

async function call(method, pathname, body) {
	const res = await fetch(`${base}${pathname}`, {
		method,
		headers: { "content-type": "application/json" },
		body: body === undefined ? undefined : JSON.stringify(body),
	});
	const text = await res.text();
	let json = null;
	try { json = JSON.parse(text); } catch { /* 非 JSON */ }
	return { status: res.status, json, text };
}

