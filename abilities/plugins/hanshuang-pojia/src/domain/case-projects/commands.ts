/**
 * 由「工程画像 + 目标系统」推出可执行命令行与构建脚本。
 *
 * 上游的脚本层是 PowerShell 为主，只能在 Windows 上跑；`setup/*.sh` 只是安装器。
 * 这里换一个方向：**不搬运脚本，生成脚本**。同一条意图在三个系统上各有落地写法，
 * 生成物是纯文本，插件本身一行都不执行——由操作者自己在终端里跑，这也让它能进 Linux。
 *
 * 三条硬约束（`src/test/case-projects.test.ts` 逐条盯着）：
 * 1. 非 Windows 系统绝不生成 `powershell` / `.ps1` / `certutil`；
 * 2. 不生成提权、不生成下载、不生成递归删除；
 * 3. 同输入同输出，方便把生成的命令贴进报告并复核。
 */
import type { BuildLanguage, CaseProject, OsKey } from "./catalog";

export interface ProjectCommand {
	/** 稳定 id，报告里按它引用。 */
	readonly id: string;
	readonly title: { readonly en: string; readonly zh: string };
	readonly command: string;
}

export function isWindows(os: OsKey): boolean {
	return os === "win32";
}

/** 构建脚本名：Windows 用 ps1（上游惯例），其余用 sh。 */
export function buildScriptName(os: OsKey): string {
	return isWindows(os) ? "build.ps1" : "build.sh";
}

/** 该语言在这个系统上的编译命令。`<slug>` 由调用方替换成工程 slug。 */
export function buildCommand(language: BuildLanguage, slug: string, os: OsKey): string {
	const win = isWindows(os);
	switch (language) {
		case "c":
			return win
				? `gcc -O2 -shared -o build\\${slug}.dll src\\*.c`
				: `cc -O2 -fPIC -shared -o build/${slug}.so src/*.c`;
		case "cs":
			return `dotnet build -c Release -o build`;
		case "rs":
			return `cargo build --release`;
		case "py":
			return win ? `py -3 -m compileall -q src` : `python3 -m compileall -q src`;
		case "java":
			return win
				? `javac -d build src\\*.java && jar cf build\\${slug}.jar -C build .`
				: `javac -d build src/*.java && jar cf build/${slug}.jar -C build .`;
		case "js":
			return win ? `node --check src\\agent.js` : `node --check src/agent.js`;
	}
}

/** 主语言：第一条构建命令用它，其余语言进「附加语言」注释。 */
export function primaryLanguage(project: CaseProject): BuildLanguage {
	return project.languages[0] ?? "py";
}

function toolCheck(tool: string, os: OsKey): string {
	return isWindows(os) ? `Get-Command ${tool} -ErrorAction SilentlyContinue` : `command -v ${tool}`;
}

function checksumCommand(os: OsKey): string {
	if (os === "win32") return `Get-FileHash -Algorithm SHA256 -Path *`;
	if (os === "darwin") return "shasum -a 256 -c SHA256SUMS.txt";
	return "sha256sum -c SHA256SUMS.txt";
}

/** 自测入口：hpkit 工具一律 Python，三个系统同一条。 */
export function selfTestCommand(os: OsKey): string {
	return isWindows(os) ? `py -3 -m unittest discover -s tools -v` : `python3 -m unittest discover -s tools -v`;
}

/**
 * 一个工程的命令序列：查工具 → 构建 → 自测 → 校验和 → 回滚提示。
 * 顺序就是值得照做的顺序；`rollback` 永远是最后一条，不让它埋在中间。
 */
export function commandsFor(project: CaseProject, os: OsKey): ProjectCommand[] {
	const slug = project.slug;
	const language = primaryLanguage(project);
	const script = buildScriptName(os);
	const runScript = isWindows(os) ? `powershell -ExecutionPolicy Bypass -File ${script}` : `bash ${script}`;

	return [
		{
			id: "probe",
			title: { en: "Check the tools this project needs", zh: "确认本工程需要的工具在不在" },
			command: project.toolchain.map(tool => toolCheck(tool, os)).join(isWindows(os) ? "; " : " && "),
		},
		{
			id: "build",
			title: { en: "Build into build/", zh: "构建到 build/" },
			command: `${runScript}   # ${buildCommand(language, slug, os)}`,
		},
		{
			id: "selftest",
			title: { en: "Run the tool self-tests before touching a sample", zh: "碰样本之前先跑工具自测" },
			command: selfTestCommand(os),
		},
		{
			id: "checksums",
			title: { en: "Verify artefacts against SHA256SUMS.txt", zh: "用 SHA256SUMS.txt 校验产物" },
			command: checksumCommand(os),
		},
		{
			id: "rollback",
			title: { en: "Restore the original bytes", zh: "还原原始字节" },
			command:
				isWindows(os)
					? `Copy-Item -Force samples\\original.bin samples\\target.bin   # 用备份覆盖，不要反向打补丁`
					: `cp -f samples/original.bin samples/target.bin   # 用备份覆盖，不要反向打补丁`,
		},
	];
}

/**
 * 生成 `build.ps1` 或 `build.sh` 的正文。
 *
 * 内容只做三件事：检查依赖、按主语言构建、写 SHA256SUMS。不联网、不提权、不删目录。
 */
export function buildScriptFor(project: CaseProject, os: OsKey): string {
	const language = primaryLanguage(project);
	const command = buildCommand(language, project.slug, os);
	const extra = project.languages.slice(1);

	if (isWindows(os)) {
		const probes = project.toolchain.map(tool => `  "${tool}"`).join(", ");
		return [
			`# ${project.slug} — build (Windows / PowerShell 5.1+)`,
			`# Generated by hanshuang-pojia. It only probes tools, builds src/, and writes SHA256SUMS.txt.`,
			`# It downloads nothing, elevates nothing, and deletes nothing.`,
			`$ErrorActionPreference = "Stop"`,
			``,
			`$needed = @(${probes})`,
			`foreach ($tool in $needed) {`,
			`  if (-not (Get-Command $tool -ErrorAction SilentlyContinue)) { Write-Warning "missing: $tool" }`,
			`}`,
			``,
			`New-Item -ItemType Directory -Force -Path build | Out-Null`,
			`${command}`,
			extra.length ? `# other languages in this archetype: ${extra.join(", ")}` : `# single-language project`,
			``,
			`Get-ChildItem build -File | ForEach-Object {`,
			`  $hash = (Get-FileHash -Algorithm SHA256 $_.FullName).Hash.ToLower()`,
			`  "$hash  build/$($_.Name)"`,
			`} | Set-Content -Encoding ascii SHA256SUMS.txt`,
			``,
			`Write-Host "built; checksums in SHA256SUMS.txt"`,
			``,
		].join("\n");
	}

	const shCommand = command.replace(/\\/g, "/");
	return [
		`#!/usr/bin/env bash`,
		`# ${project.slug} — build (Linux / macOS)`,
		`# Generated by hanshuang-pojia. It only probes tools, builds src/, and writes SHA256SUMS.txt.`,
		`# It downloads nothing, elevates nothing, and deletes nothing.`,
		`set -euo pipefail`,
		``,
		`for tool in ${project.toolchain.join(" ")}; do`,
		`  command -v "$tool" >/dev/null 2>&1 || echo "warning: missing $tool" >&2`,
		`done`,
		``,
		`mkdir -p build`,
		`${shCommand}`,
		extra.length ? `# other languages in this archetype: ${extra.join(", ")}` : `# single-language project`,
		``,
		`if command -v sha256sum >/dev/null 2>&1; then`,
		`  (cd build && sha256sum ./* | sed 's|\\./|build/|' > ../SHA256SUMS.txt)`,
		`else`,
		`  (cd build && shasum -a 256 ./* | sed 's|\\./|build/|' > ../SHA256SUMS.txt)`,
		`fi`,
		``,
		`echo "built; checksums in SHA256SUMS.txt"`,
		``,
	].join("\n");
}

