/**
 * 运行时 DEX dump：脚本模板 + 日志解析。
 *
 * 加壳样本的类在磁盘上是空的，真身只在内存里 —— ART 把 `classes.dex`（或壳自己解出来的
 * dex）映射进可写内存之后才实例化。所以这里做的是**扫描 + 抄回**，不是反编译：
 *
 * 1. `Process.enumerateRanges("rw-")` 只看可写段，不碰代码段；
 * 2. 在段内找 `64 65 78 0a 30 33`（`dex\n03`）并校验 `header_size == 0x70`、
 *    `endian_tag == 0x12345678`、`file_size` 落在合理区间 —— 三个字段都对上才算 dex，
 *    只比 magic 会把常量池里的字符串当成文件头；
 * 3. 命中后按 32 KiB 分块 base64 走 stdout，主机侧拼回文件、算 SHA-256、按摘要去重。
 *
 * 为什么不直接让脚本写文件：设备侧目录要么不可写（app 沙盒外），要么写完还得 `adb pull`
 * 一次。走 stdout 少一步权限，也让整个 dump 过程在 frida 日志里可复查。
 */

import { fromBase64 } from "../base64";

export interface DexDumpOptions {
	/** 最多抄回几个 dex：再多就是整包重打包，不是「看一眼壳里有什么」。 */
	maxDex?: number;
	/** spawn 之后等多久开始扫，给 ART 留出解壳时间。 */
	delayMs?: number;
	/** 单个 dex 的体积上限，防止把 200 MB 的 mmap 当 dex 抄。 */
	limitMb?: number;
	/** 脚本头部注释里记一笔来源。 */
	source?: string;
}

export const DEFAULT_MAX_DEX = 8;
export const DEFAULT_DELAY_MS = 1_500;
export const DEFAULT_LIMIT_MB = 64;
/**
 * 3 的倍数：base64 按 3 字节一组编码，块长不是 3 的倍数时每块末尾都会带 `=`，
 * 手工把多段 base64 字符串拼起来就得到一条中间带 padding 的非法串。主机侧逐块解码
 * 已经对了，这个常量是给「拿日志手拼」的人留的双保险。
 */
export const CHUNK_BYTES = 32_766;

/** 一条 dump 事件；`data` 只在 `dex-chunk` 上有。 */
export interface DexDumpEvent {
	event: "dex-start" | "dex-chunk" | "dex-end" | "done" | "note";
	index?: number;
	seq?: number;
	size?: number;
	data?: string;
	dumped?: number;
	message?: string;
}

export interface ParsedDexDump {
	/** `bytes` 是逐块解码后拼好的字节：不拼 base64 字符串，否则中间段会残留 padding。 */
	dexes: { index: number; size: number; bytes: Uint8Array }[];
	notes: string[];
	done: boolean;
}

/**
 * 生成整份脚本。脚本里刻意不依赖 `Java.use`：壳可能把 ART 的 Java 桥改坏，而
 * `Process` / `Memory` 是 Native 层，壳动不了。
 */
export function buildDexDumpScript(options: DexDumpOptions = {}): string {
	const maxDex = Math.max(1, Math.min(32, options.maxDex ?? DEFAULT_MAX_DEX));
	const delayMs = Math.max(200, Math.min(30_000, options.delayMs ?? DEFAULT_DELAY_MS));
	const limitMb = Math.max(4, Math.min(512, options.limitMb ?? DEFAULT_LIMIT_MB));

	return [
		"// Runtime DEX dump generated by hanshuang-pojia (frida_dump).",
		`// source: ${options.source ?? "(unspecified)"} · max ${maxDex} dex · scan starts ${delayMs} ms after spawn`,
		"//",
		"// Reads writable memory only, validates magic + header_size + endian_tag + file_size,",
		"// then streams each candidate to stdout as base64 JSON lines. Nothing is written on the device.",
		"",
		`var MAX_DEX = ${maxDex};`,
		`var LIMIT_BYTES = ${limitMb} * 1024 * 1024;`,
		`var CHUNK = ${CHUNK_BYTES};`,
		`var SCAN_DELAY_MS = ${delayMs};`,
		"",
		'var B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";',
		"",
		"function emit(payload) {",
		"  try { console.log(JSON.stringify(payload)); } catch (error) { }",
		"}",
		"",
		"function base64(bytes) {",
		'  var out = "";',
		"  var length = bytes.length;",
		"  for (var index = 0; index < length; index += 3) {",
		"    var a = bytes[index];",
		"    var b = index + 1 < length ? bytes[index + 1] : 0;",
		"    var c = index + 2 < length ? bytes[index + 2] : 0;",
		"    out += B64[a >> 2] + B64[((a & 3) << 4) | (b >> 4)];",
		'    out += index + 1 < length ? B64[((b & 15) << 2) | (c >> 6)] : "=";',
		'    out += index + 2 < length ? B64[c & 63] : "=";',
		"  }",
		"  return out;",
		"}",
		"",
		"// Returns the file size of a plausible DEX header at addr, or -1.",
		"function dexSizeAt(addr) {",
		"  var magic;",
		"  try { magic = new Uint8Array(addr.readByteArray(8)); } catch (error) { return -1; }",
		"  if (magic[0] !== 0x64 || magic[1] !== 0x65 || magic[2] !== 0x78 || magic[3] !== 0x0a) return -1;",
		"  var headerSize, endianTag, fileSize;",
		"  try {",
		"    fileSize = addr.add(0x20).readU32();",
		"    headerSize = addr.add(0x24).readU32();",
		"    endianTag = addr.add(0x28).readU32();",
		"  } catch (error) { return -1; }",
		"  if (headerSize !== 0x70 || endianTag !== 0x12345678) return -1;",
		"  if (fileSize < 0x70 || fileSize > LIMIT_BYTES) return -1;",
		"  return fileSize;",
		"}",
		"",
		"function inRange(range, addr, size) {",
		"  var start = addr;",
		"  var end = addr.add(size);",
		"  var rangeEnd = range.base.add(range.size);",
		"  return start.compare(range.base) >= 0 && end.compare(rangeEnd) <= 0;",
		"}",
		"",
		"function dumpAt(addr, size, index) {",
		'  emit({ event: "dex-start", index: index, size: size });',
		"  var seq = 0;",
		"  for (var offset = 0; offset < size; offset += CHUNK) {",
		"    var length = Math.min(CHUNK, size - offset);",
		"    var bytes;",
		"    try { bytes = new Uint8Array(addr.add(offset).readByteArray(length)); } catch (error) {",
		'      emit({ event: "note", index: index, message: "read failed at offset " + offset });',
		"      break;",
		"    }",
		'    emit({ event: "dex-chunk", index: index, seq: seq, data: base64(bytes) });',
		"    seq += 1;",
		"  }",
		'  emit({ event: "dex-end", index: index, size: size });',
		"}",
		"",
		"function scan() {",
		"  var dumped = 0;",
		'  var seen = {};',
		'  var ranges;',
		'  try { ranges = Process.enumerateRanges("rw-"); } catch (error) {',
		'    emit({ event: "note", message: "enumerateRanges failed: " + String(error) });',
		'    emit({ event: "done", dumped: 0 });',
		"    return;",
		"  }",
		"  for (var r = 0; r < ranges.length && dumped < MAX_DEX; r += 1) {",
		"    var range = ranges[r];",
		"    var matches;",
		'    try { matches = Memory.scanSync(range.base, range.size, "64 65 78 0a 30 33"); } catch (error) { continue; }',
		"    for (var m = 0; m < matches.length && dumped < MAX_DEX; m += 1) {",
		"      var addr = matches[m].address;",
		"      var size = dexSizeAt(addr);",
		"      if (size < 0) continue;",
		"      if (!inRange(range, addr, size)) continue;",
		"      // The same dex can be mapped twice by dexopt; identical size is the cheap filter here,",
		"      // and the host still dedupes by SHA-256 after reassembly.",
		"      if (seen[size]) continue;",
		"      seen[size] = true;",
		"      dumpAt(addr, size, dumped);",
		"      dumped += 1;",
		"    }",
		"  }",
		'  emit({ event: "done", dumped: dumped });',
		"}",
		"",
		"setTimeout(scan, SCAN_DELAY_MS);",
		"",
	].join("\n");
}

/**
 * 解析 frida 日志里的事件行。
 *
 * frida CLI 在 `-o` 写文件时仍会夹带自己的提示行（`Spawning …`、`[Local::…]->`），所以每一行
 * 先定位第一个 `{`，再尝试 JSON.parse；解析失败的行只记一条 note，不当错误 —— 那些行本来就
 * 不是我们写的。
 */
export function parseDexDumpLog(text: string): ParsedDexDump {
	const dexes = new Map<number, { size: number; chunks: Map<number, string> }>();
	const notes: string[] = [];
	let done = false;

	for (const raw of text.split("\n")) {
		const start = raw.indexOf("{");
		if (start < 0) continue;
		let event: DexDumpEvent;
		try {
			event = JSON.parse(raw.slice(start)) as DexDumpEvent;
		} catch {
			if (notes.length < 6) notes.push(`unparsed log line: ${raw.trim().slice(0, 120)}`);
			continue;
		}
		if (!event || typeof event.event !== "string") continue;

		if (event.event === "dex-start" && typeof event.index === "number") {
			dexes.set(event.index, { size: event.size ?? 0, chunks: new Map() });
			continue;
		}
		if (event.event === "dex-chunk" && typeof event.index === "number" && typeof event.seq === "number" && typeof event.data === "string") {
			dexes.get(event.index)?.chunks.set(event.seq, event.data);
			continue;
		}
		if (event.event === "dex-end" && typeof event.index === "number") {
			const entry = dexes.get(event.index);
			if (entry && typeof event.size === "number") entry.size = event.size;
			continue;
		}
		if (event.event === "done") {
			done = true;
			continue;
		}
		if (event.event === "note" && typeof event.message === "string" && notes.length < 8) notes.push(event.message);
	}

	const assembled: ParsedDexDump["dexes"] = [];
	for (const [index, entry] of Array.from(dexes.entries()).sort((left, right) => left[0] - right[0])) {
		const ordered = Array.from(entry.chunks.entries()).sort((left, right) => left[0] - right[0]);
		if (ordered.length === 0) continue;
		// 逐块解码再拼字节：拼 base64 字符串会把每段的 `=` 留在中间，解不出原文件。
		const parts: Uint8Array[] = [];
		for (const [, chunk] of ordered) {
			try {
				parts.push(fromBase64(chunk));
			} catch {
				if (notes.length < 8) notes.push(`chunk ${index} of dex #${index} is not valid base64`);
			}
		}
		const total = parts.reduce((sum, part) => sum + part.byteLength, 0);
		const bytes = new Uint8Array(total);
		let offset = 0;
		for (const part of parts) {
			bytes.set(part, offset);
			offset += part.byteLength;
		}
		if (bytes.byteLength === 0) continue;
		assembled.push({ index, size: entry.size, bytes });
	}

	return { dexes: assembled, notes, done };
}

/** 跑起来要用户自己补的命令行，写进工具输出而不是脚本里。 */
export function fridaDumpHint(packageName: string | null, scriptName: string): string {
	const pkg = packageName ?? "<package-name>";
	return [
		`Spawn and dump: frida -U -f ${pkg} -l ${scriptName} -o frida-dump.log -q`,
		`Or attach to a running app: frida -U ${pkg} -l ${scriptName} -o frida-dump.log -q`,
		"The script streams base64 JSON lines on stdout, so `-o` keeps them in a file you can parse with",
		"`frida_dump` again (`mode: \"assemble\"`) or by hand. Needs frida-server running on the device.",
	].join("\n");
}
