#!/usr/bin/env node
/**
 * 把 src/content/packs/*.md 编译成随包发布的提示词包索引。
 *
 * 索引只留元数据（标题、摘要、注入模式、出处、字节数、sha256），正文不进 JS 分块：
 * 包的正文会随包发到 dist/assets/packs/，由 `loadPackBody` 按需读取。
 * 与 docs / precedents 同一条边界 —— 只有启动时非有不可的才进分块。
 *
 * 用法：
 *   node scripts/sync-packs.mjs            重新生成 src/domain/inject/packs.generated.ts
 *   node scripts/sync-packs.mjs --check    只校验生成物是否与正文一致（CI 用）
 */
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const packsDir = join(root, "src/content/packs");
const outPath = join(root, "src/domain/inject/packs.generated.ts");
const check = process.argv.includes("--check");

/** 正文头部的 key: value 块；缺字段直接失败，不猜默认值。 */
function readPack(name) {
	const text = readFileSync(join(packsDir, name), "utf8").replace(/\r\n/g, "\n");
	const match = /^---\n([\s\S]*?)\n---\n/.exec(text);
	if (!match) throw new Error(`${name}: missing front matter`);
	const meta = {};
	for (const line of match[1].split("\n")) {
		const at = line.indexOf(":");
		if (at === -1) continue;
		meta[line.slice(0, at).trim()] = line.slice(at + 1).trim();
	}
	for (const key of ["title", "summary", "mode", "provenance"]) {
		if (!meta[key]) throw new Error(`${name}: front matter missing ${key}`);
	}
	const body = text.slice(match[0].length);
	if (body.trim().length === 0) throw new Error(`${name}: empty body`);
	return {
		id: name.replace(/\.md$/, ""),
		title: meta.title,
		summary: meta.summary,
		mode: meta.mode,
		provenance: meta.provenance,
		chars: body.length,
		sha256: createHash("sha256").update(Buffer.from(text, "utf8")).digest("hex"),
	};
}

function build() {
	return readdirSync(packsDir)
		.filter(name => name.endsWith(".md"))
		.sort()
		.map(readPack);
}

function render(packs) {
	const banner = [
		"// Generated by scripts/sync-packs.mjs — do not edit by hand.",
		"// Source of truth: src/content/packs/<id>.md (front matter + body).",
		"// Bodies are NOT inlined: they ship under dist/assets/packs/ and load on demand.",
		"// Run `node scripts/sync-packs.mjs` after editing a pack.",
	].join("\n");

	const rows = packs
		.map(
			pack => `\t{
\t\tid: ${JSON.stringify(pack.id)},
\t\ttitle: ${JSON.stringify(pack.title)},
\t\tsummary: ${JSON.stringify(pack.summary)},
\t\tmode: ${JSON.stringify(pack.mode)} as PackMode,
\t\tprovenance: ${JSON.stringify(pack.provenance)},
\t\tchars: ${pack.chars},
\t\tsha256: ${JSON.stringify(pack.sha256)},
\t},`,
		)
		.join("\n");

	return `${banner}

/** 注入模式与提示词库一致：append / prepend / override。 */
export type PackMode = "append" | "prepend" | "override";

export interface PromptPackEntry {
	/** 正文文件名（不含扩展名），也是 assets/packs/<id>.md 的 id。 */
	readonly id: string;
	readonly title: string;
	readonly summary: string;
	readonly mode: PackMode;
	/** 出处：哪个仓库的哪个文件，注明是结构重写还是原文搬运。 */
	readonly provenance: string;
	/** 正文长度（字符），用于在界面上判断要不要分段读。 */
	readonly chars: number;
	readonly sha256: string;
}

/** 随包发布的提示词包，按 id 升序。 */
export const PACKS: readonly PromptPackEntry[] = [
${rows}
];
`;
}

const packs = build();
const next = render(packs);

if (check) {
	let current = "";
	try {
		current = readFileSync(outPath, "utf8");
	} catch {
		console.error(`packs: ${outPath} is missing — run \`node scripts/sync-packs.mjs\``);
		process.exit(1);
	}
	if (current !== next) {
		console.error("packs: generated index is stale — run `node scripts/sync-packs.mjs`");
		process.exit(1);
	}
	console.log(`packs: ${packs.length} pack(s) up to date`);
} else {
	writeFileSync(outPath, next);
	console.log(`packs: wrote ${packs.length} pack(s) to ${outPath}`);
}
