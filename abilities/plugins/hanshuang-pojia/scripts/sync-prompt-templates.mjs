#!/usr/bin/env node
/**
 * 把 `agent/prompts/templates/*.md` 编译成「预置提示词模板」索引。
 *
 * 与 packs / docs 同一条边界（ADR 0009）：索引进 JS 分块只留元数据（id、标题、摘要、
 * 字符数、sha256），正文随包发到 `dist/assets/prompts/templates/`，由面板按需读取。
 *
 * 模板与「提示词包」的区别：包是我方撰写的作战契约（`src/content/packs/`），
 * 模板是随工具分发、用户可自行修改再注入的现成词表（`agent/prompts/templates/`）。
 * 两者的生命周期不同，所以索引也分开。
 *
 * 用法：
 *   node scripts/sync-prompt-templates.mjs            重新生成
 *   node scripts/sync-prompt-templates.mjs --check    只校验是否过期（CI）
 */
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "agent/prompts/templates");
const outPath = join(root, "src/domain/prompt-templates.generated.ts");
const check = process.argv.includes("--check");

/**
 * 六个模板的首个 `#` 标题都是同一句「中转站保护」，拿它当标题会让列表里六条重名。
 * 所以标题用文件名（就是用户认的那个名字），摘要 = 第一个小节标题 + 首段正文，
 * 让变体 B / v1.2 / v3 / v4 / v4-claude / v5 一眼能分开。
 */
function summarise(text, id) {
	const lines = text.replace(/\r\n/g, "\n").split("\n");
	const heading = (lines.find(line => line.startsWith("# ")) ?? "").replace(/^#\s*/, "").trim();
	const body = lines
		.map(line => line.trim())
		.filter(line => line.length > 0 && !line.startsWith("#"))
		.join(" ");
	return { title: id, summary: `${heading ? `${heading}。` : ""}${body}`.slice(0, 120) };
}

function build() {
	return readdirSync(dir)
		.filter(name => name.endsWith(".md"))
		.sort()
		.map(name => {
			const text = readFileSync(join(dir, name), "utf8");
			const id = name.replace(/\.md$/, "");
			const { title, summary } = summarise(text, id);
			return {
				id,
				file: name,
				title,
				summary,
				chars: text.length,
				sha256: createHash("sha256").update(Buffer.from(text, "utf8")).digest("hex"),
			};
		});
}

function render(templates) {
	const banner = [
		"// Generated by scripts/sync-prompt-templates.mjs — do not edit by hand.",
		"// Source of truth: agent/prompts/templates/<id>.md",
		"// Bodies are NOT inlined: they ship under dist/assets/prompts/templates/ and load on demand.",
	].join("\n");

	const rows = templates
		.map(
			template => `\t{
\t\tid: ${JSON.stringify(template.id)},
\t\tfile: ${JSON.stringify(template.file)},
\t\ttitle: ${JSON.stringify(template.title)},
\t\tsummary: ${JSON.stringify(template.summary)},
\t\tchars: ${template.chars},
\t\tsha256: ${JSON.stringify(template.sha256)},
\t},`,
		)
		.join("\n");

	return `${banner}

export interface PromptTemplateEntry {
	/** 文件名（不含 .md），也是 assets/prompts/templates/<id>.md 的 id。 */
	readonly id: string;
	readonly file: string;
	readonly title: string;
	readonly summary: string;
	readonly chars: number;
	readonly sha256: string;
}

/** 随包的预置提示词模板，按文件名升序。 */
export const PROMPT_TEMPLATES: readonly PromptTemplateEntry[] = [
${rows}
];
`;
}

const templates = build();
const next = render(templates);

if (check) {
	let current = "";
	try {
		current = readFileSync(outPath, "utf8");
	} catch {
		console.error(`templates: ${outPath} is missing — run \`node scripts/sync-prompt-templates.mjs\``);
		process.exit(1);
	}
	if (current !== next) {
		console.error("templates: generated index is stale — run `node scripts/sync-prompt-templates.mjs`");
		process.exit(1);
	}
	console.log(`templates: ${templates.length} template(s) up to date`);
} else {
	writeFileSync(outPath, next);
	console.log(`templates: wrote ${templates.length} template(s) to ${outPath}`);
}
