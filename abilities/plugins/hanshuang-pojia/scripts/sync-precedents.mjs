#!/usr/bin/env node
/**
 * 把 cases/ 下的先例包编译成随包发布的 TS 模块。
 *
 * 先例包是给人读、给人复制的目录（case.json + README/scope + docs/{method,defense}）；
 * 插件运行时只能读到 dist 里的东西，所以正文必须内联成字符串常量，
 * 不能指望 `cases/` 目录跟着 .astraviapkg 走。
 *
 * 案例原文（补丁全表、算法推导、复现脚本）不内联：它以纯文本放在
 * src/content/docs/cases/<slug>/ 随包发布，由 docs 库惰性加载，
 * 先例包只留 caseDocs 指针。这样主 JS 分块不会因为语料变厚而变大。
 *
 * 用法：
 *   node scripts/sync-precedents.mjs            重新生成 src/domain/case/precedents.generated.ts
 *   node scripts/sync-precedents.mjs --check    只校验生成物是否与 cases/ 一致
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { precedentDirs, readPackage } from "./lib/precedent-package.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const casesDir = join(root, "cases");
const docsDir = join(root, "src/content/docs");
const outPath = join(root, "src/domain/case/precedents.generated.ts");

function build() {
	return precedentDirs(casesDir).map(dir => {
		try {
			return readPackage({ casesDir, docsDir, dir });
		} catch (error) {
			console.error(error.message);
			process.exit(1);
		}
	});
}

function render(precedents) {
	const banner = [
		"// Generated by scripts/sync-precedents.mjs — do not edit by hand.",
		"// Source of truth: cases/<slug>/{case.json,README.md,scope.md,docs/{method,defense}.md,...}",
		"// Run `node scripts/sync-precedents.mjs` after editing a precedent package.",
		"// Case studies themselves live in src/content/docs/cases/<slug>/ and load lazily.",
	].join("\n");

	return `${banner}

export interface PrecedentDoc {
\t/** Package-relative file name, e.g. \`docs/method.md\`. */
\treadonly id: string;
\treadonly text: string;
}

export interface PrecedentSource {
\t/** Where the package was derived from, e.g. \`seep-kit 2.0\`. */
\treadonly library: string;
\t/** Upstream entry the digest was written from, e.g. \`Tool/cases/项目J\`. */
\treadonly entry: string;
}

export interface PrecedentTool {
	readonly id: string;
	/** File name inside the package's tools/ directory. */
	readonly entry: string;
	readonly purpose: string;
	readonly args: readonly string[];
	readonly expect: string;
}

export interface PrecedentToolkit {
	/** Interpreter family: python, powershell or node. */
	readonly runtime: string;
	readonly platforms: readonly string[];
	readonly tools: readonly PrecedentTool[];
}

export interface ShippedPrecedent {
\treadonly slug: string;
\treadonly title: string;
\treadonly summary: string;
\t/** Lower-case fragments the query is matched against. */
\treadonly signals: readonly string[];
\t/** Preset to start from when the package is copied into a real case. */
\treadonly preset: string;
\t/** Field-journal documents this precedent is derived from. */
\treadonly fieldNotes: readonly string[];
\t/** Document-library ids holding the full case study, read with read_doc. */
\treadonly caseDocs: readonly string[];
\t/** Present when the package was derived from an upstream case library. */
	readonly source?: PrecedentSource;
	/** Runnable tools the package ships; empty only if the package is text-only. */
	readonly tools: PrecedentToolkit;
\treadonly docs: readonly PrecedentDoc[];
}

export const SHIPPED_PRECEDENTS: readonly ShippedPrecedent[] = ${JSON.stringify(precedents, null, "\t")};

export const PRECEDENT_COUNT = SHIPPED_PRECEDENTS.length;

/** 稳定排序的 slug 清单，供「可用先例」提示复用。 */
export function shippedPrecedentSlugs(): string {
\treturn SHIPPED_PRECEDENTS.map(precedent => precedent.slug).join(", ");
}
`;
}

const precedents = build();
const next = render(precedents);

if (process.argv.includes("--check")) {
	const current = existsSync(outPath) ? readFileSync(outPath, "utf8") : "";
	if (current !== next) {
		console.error(`precedent bundle is stale (${precedents.length} packages) — run node scripts/sync-precedents.mjs`);
		process.exit(1);
	}
	console.log(`precedents ok: ${precedents.length} packages`);
} else {
	writeFileSync(outPath, next);
	console.log(`wrote ${relative(root, outPath)}: ${precedents.length} packages`);
}
