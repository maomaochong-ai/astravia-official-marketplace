CHAIN_MD = """# payload chain

Three stages, bottom-up; each one's output feeds the next.

| stage | file | what it settles | placeholders to fill |
| --- | --- | --- | --- |
| 1 carrier | `{blob_name}` | packs the payload into a self-describing, self-checking blob | none (the body belongs to discovery) |
| 2 mapper | `loader.py` | allocates in the target and jumps | `TARGET_RVA` |
| 3 injector | `injector.py` | moves the blob in, repoints the entry, keeps the rollback | `SLACK_CAVE`, `TARGET_FILE_OFFSET`, `ORIGINAL_BYTES`, `PATCH_BYTES` |

## Why the holes are named

The upstream equivalent writes addresses as constants. Change the target and every one of them
becomes a *silent* error: written to the wrong offset, patched in the wrong place, rolled back from
the wrong bytes. None of those raise; they produce a plausible-looking result. Named placeholders
make "how many numbers are still missing" a countable fact.

{placeholder_table}

## Order

1. `triage_binary` for format, sections and slack;
2. `disasm` / `list_code_symbols` for the entry and the cave;
3. fill the placeholders; run `loader.py` locally first (shape only, no jump);
4. `injector.py` prints the plan -- confirm the rollback is last;
5. the real run goes through `run_case_tool` (self-test gate first) or the host agent.

## Boundary

This generates a **shape**, not a working payload. Without the discovery pass these four files say
how the chain connects, and nothing about whether any particular target accepts it.
"""


def _placeholder_table() -> str:
    rows = ["| placeholder | meaning |", "| --- | --- |"]
    rows.extend("| `%s` | %s |" % (key, meaning) for key, meaning in PLACEHOLDERS)
    return "\n".join(rows)


def render_chain(platform: str, target_name: str) -> dict:
    blob_name = "payload.bin"
    blob = build_blob(default_body(platform), "payload")
    placeholders = _placeholders_block()
    return {
        blob_name: blob,
        "loader.py": LOADER.format(placeholders=placeholders, blob_name=blob_name, magic=MAGIC.decode("ascii")).encode("utf-8"),
        "injector.py": INJECTOR.format(placeholders=placeholders, target_name=target_name, blob_name=blob_name).encode("utf-8"),
        "chain.md": CHAIN_MD.format(blob_name=blob_name, placeholder_table=_placeholder_table()).encode("utf-8"),
    }


def write_outputs(out_dir, files):
    os.makedirs(out_dir, exist_ok=True)
    written = []
    for name, content in sorted(files.items()):
        path = os.path.join(out_dir, name)
        with open(path, "wb") as handle:
            handle.write(content)
        written.append(path)
    return written


def main(options):
    platform = options.get("platform") or "win"
    if platform not in ("win", "linux"):
        raise cli.UsageError("--platform must be win or linux")
    target_name = options.get("target-name") or ("demo.elf" if platform == "linux" else "demo.exe")
    out_dir = options.get("out") or "out"

    files = render_chain(platform, target_name)
    written = write_outputs(out_dir, files)

    sys.stdout.write("platform: {}  target: {}\n".format(platform, target_name))
    for path in written:
        sys.stdout.write("  wrote {} ({} bytes)\n".format(path, os.path.getsize(path)))
    sys.stdout.write("\nplaceholders still to fill during discovery:\n")
    for key, meaning in PLACEHOLDERS:
        sys.stdout.write("  {:<20} {}\n".format(key, meaning))
    sys.stdout.write("\nUntil they are filled, these files describe the chain, not the target.\n")
    return cli.EXIT_OK


def self_test():
    results = [selftest.run() == cli.EXIT_OK]

    body = b"\x00" * 64
    first = build_blob(body, "payload")
    results.append(("blob is deterministic", first == build_blob(body, "payload")))

    parsed = parse_blob(first)
    results.append(("blob round-trips", parsed["body"] == body))
    results.append(("blob carries its own sha256", parsed["sha256"] == hashlib.sha256(body).hexdigest()))

    tampered = bytearray(first)
    tampered[20] ^= 0xFF
    try:
        parse_blob(bytes(tampered))
        results.append(("tampered body is rejected", False))
    except ValueError:
        results.append(("tampered body is rejected", True))

    try:
        parse_blob(b"NOPE" + first[4:])
        results.append(("bad magic is rejected", False))
    except ValueError:
        results.append(("bad magic is rejected", True))

    win = render_chain("win", "demo.exe")
    lin = render_chain("linux", "demo.elf")
    results.append(("both platforms render the same four files", set(win) == set(lin) == {"payload.bin", "loader.py", "injector.py", "chain.md"}))

    injector_text = win["injector.py"].decode("utf-8")
    chain_text = win["chain.md"].decode("utf-8")
    results.append(
        (
            "every placeholder is named in the generated files",
            all(key in injector_text or key in chain_text for key, _ in PLACEHOLDERS),
        )
    )

    # The digest is the last 32 bytes of the file, so "body ends in ret" reads the parsed body.
    results.append(("linux body ends in ret", parse_blob(lin["payload.bin"])["body"][-1:] == b"\xc3"))
    results.append(("win body stays inert zeros", parse_blob(win["payload.bin"])["body"] == b"\x00" * 64))

    passed = sum(1 for item in results if (item[1] if isinstance(item, tuple) else item))
    for item in results:
        if isinstance(item, tuple):
            sys.stdout.write("[{}] chain: {}\n".format("PASS" if item[1] else "FAIL", item[0]))
    sys.stdout.write("\npayload_chain self test: {}/{} assertions passed\n".format(passed, len(results)))
    return cli.EXIT_OK if passed == len(results) else cli.EXIT_SELFTEST


FLAGS = ()
VALUES = ("platform", "target-name", "out")


if __name__ == "__main__":
    sys.exit(cli.run(main, self_test, FLAGS, VALUES))
