#!/usr/bin/env python3
"""Find boolean-return stubs and build the equal-length patch table for them.

Case G's pass criterion was a single branch: a method named like a licence check
returned a constant. The durable part of that finding is not the offset, it is
the *shape* of the stub, which is why this tool matches bytes and not names:

* ``B8 00 00 00 00 C3``  mov eax, 0 ; ret   (returns false on x86/x64)
* ``B8 01 00 00 00 C3``  mov eax, 1 ; ret   (already returns true)
* ``00 00 80 52 C0 03 5F D6``  mov w0, #0 ; ret  (AArch64)
* ``20 00 80 52 C0 03 5F D6``  mov w0, #1 ; ret  (AArch64)
* ``31 C0 C3`` / ``33 C0 C3``  xor eax, eax ; ret  (reported, not patched)

The patch row this tool emits flips only the immediate, so the original and the
patched byte strings are the same length. That is deliberate: an unequal-length
edit turns a four-byte constant into a code-cave problem, and every case that
did it the other way had to redo the table for the next build.

usage:
    python3 bool_stub_scan.py --sample gate.dll
    python3 bool_stub_scan.py --sample gate.dll --table findings/
    python3 bool_stub_scan.py --self-test
"""

import os
import sys

_here = os.path.dirname(os.path.abspath(sys.argv[0]))
for _candidate in (_here, os.path.abspath(os.path.join(_here, "..", "..", "_shared"))):
    if os.path.isdir(os.path.join(_candidate, "hpkit")):
        sys.path.insert(0, _candidate)
        break

from hpkit import cli, fixtures, patch, pe, scan  # noqa: E402

# name, pattern, family, meaning, patchable
STUBS = (
    ("x86-x64 false", "B8 00 00 00 00 C3", "x86", "returns 0 from a bool method", True),
    ("x86-x64 true", "B8 01 00 00 00 C3", "x86", "already returns 1", False),
    ("x86-x64 other", "B8 ?? 00 00 00 C3", "x86", "returns a non-boolean constant", False),
    ("aarch64 false", "00 00 80 52 C0 03 5F D6", "arm64", "mov w0,#0 ; ret", True),
    ("aarch64 true", "20 00 80 52 C0 03 5F D6", "arm64", "mov w0,#1 ; ret", False),
    ("x86-x64 xor", "31 C0 C3", "x86", "xor eax,eax ; ret", False),
    ("x86-x64 xor alt", "33 C0 C3", "x86", "xor eax,eax ; ret (alternate encoding)", False),
)

FAMILIES = {
    "x86-x64 false": ("B8 00 00 00 00", "B8 01 00 00 00"),
    "aarch64 false": ("00 00 80 52", "20 00 80 52"),
}


def find_stubs(image):
    hits = []
    for name, pattern, family, meaning, patchable in STUBS:
        if name.endswith("other"):
            continue
        for hit in scan.find_in_image(image, pattern):
            section = image.section_for(hit["rva"]) if hit["rva"] is not None else None
            hits.append(
                {
                    "name": name,
                    "family": family,
                    "meaning": meaning,
                    "patchable": patchable,
                    "rva": hit["rva"],
                    "file_offset": hit["file_offset"],
                    "section": section.name if section else "<none>",
                    "executable": bool(section and section.executable),
                }
            )
    hits.sort(key=lambda row: (row["file_offset"], row["name"]))
    return hits


def family_matches(family, arch):
    if not arch:
        return True
    if family == "arm64":
        return arch.startswith("arm")
    return arch.startswith("x86")


def patch_rows(hits, arch=None):
    """Only the false stubs become rows; each flips the immediate in place.

    Hits from the other architecture family are skipped: a row that cannot apply
    is worse than no row, because it looks like a plan.
    """
    rows = []
    for hit in hits:
        if not hit["patchable"]:
            continue
        if not family_matches(hit["family"], arch):
            continue
        original, patched = FAMILIES[hit["name"]]
        rows.append(
            [
                "0x{:X}".format(hit["rva"]) if hit["rva"] is not None else "file+0x{:X}".format(hit["file_offset"]),
                original,
                patched,
                "{} at {} ({})".format(hit["name"], hit["section"], "isLicensed-style bool"),
            ]
        )
    return rows


def render_table(rows):
    lines = ["# patch table generated by bool_stub_scan.py", "# address | original | patched | note"]
    for row in rows:
        lines.append("{} | {} | {} | {}".format(row[0], row[1], row[2], row[3]))
    return "\n".join(lines) + "\n"


def main(options):
    cli.require(options, "sample")
    image = pe.read(options["sample"])
    hits = find_stubs(image)

    report = cli.Report("boolean-return stub scan")
    report.field("sample", image.path)
    report.field("format", "{} {} {}-bit".format(image.kind, image.arch, image.bits))
    report.field("sha256", image.sha256)

    report.heading("stubs found")
    if hits:
        report.table(
            ["pattern", "section", "rva", "file offset", "meaning", "patchable"],
            [
                [
                    hit["name"],
                    hit["section"],
                    "0x{:X}".format(hit["rva"]) if hit["rva"] is not None else "?",
                    "0x{:X}".format(hit["file_offset"]),
                    hit["meaning"],
                    "yes" if hit["patchable"] else "no",
                ]
                for hit in hits
            ],
        )
    else:
        report.line("none. A bool gate that is not a constant return needs the branch read, not a byte pattern.")

    mismatched = [
        hit
        for hit in hits
        if (hit["family"] == "arm64" and image.arch.startswith("x86"))
        or (hit["family"] == "x86" and image.arch.startswith("arm"))
    ]
    if mismatched:
        report.heading("warnings")
        report.bullet(
            "{} hit(s) belong to the other architecture family than {}; check the pattern table before trusting them.".format(
                len(mismatched), image.arch
            )
        )

    rows = patch_rows(hits, image.arch)
    report.heading("patch rows")
    if rows:
        report.table(["address", "original", "patched", "note"], rows)
        report.bullet("Original and patched bytes have equal length, so the edit stays inside the instruction.")
        report.bullet("Apply with patch.py semantics: refuse on mismatch, verify the diff is only this site.")
    else:
        report.line("no patchable false stub; nothing to write.")

    out_dir = options.get("table")
    if out_dir and rows:
        os.makedirs(out_dir, exist_ok=True)
        target = os.path.join(out_dir, "patch-table.txt")
        with open(target, "w", encoding="utf-8") as handle:
            handle.write(render_table(rows))
        report.field("table", target)

    report.emit()
    return cli.EXIT_OK


def self_test():
    from hpkit import selftest

    results = [selftest.run() == cli.EXIT_OK]

    with fixtures.Workspace() as workspace:
        data = bytearray(fixtures.synthetic_pe())
        data[0x280 : 0x280 + 6] = bytes.fromhex("B800000000C3")
        data[0x2A0 : 0x2A0 + 6] = bytes.fromhex("B801000000C3")
        data[0x2C0 : 0x2C0 + 8] = bytes.fromhex("00008052C0035FD6")
        path = workspace.write("gate.exe", bytes(data))
        image = pe.read(path)
        hits = find_stubs(image)
        kinds = {hit["name"] for hit in hits}
        results.append("x86-x64 false" in kinds)
        results.append("x86-x64 true" in kinds)
        results.append("aarch64 false" in kinds)
        false_hit = next(hit for hit in hits if hit["name"] == "x86-x64 false")
        results.append(false_hit["rva"] == 0x1080 and false_hit["file_offset"] == 0x280)
        results.append(false_hit["executable"])

        rows = patch_rows(hits, image.arch)
        results.append(any("B8 00 00 00 00" in row[1] for row in rows))
        results.append(all(len(row[1].split()) == len(row[2].split()) for row in rows))
        # The generated row must actually apply: parse it back through patch.py.
        sites = patch.parse_table(render_table(rows), address_kind="rva")
        detail = patch.check(image.data, sites, image)
        results.append(all(row["state"] == "original" for row in detail))
        patched, _ = patch.apply(image.data, sites, image)
        results.append(patched[false_hit["file_offset"] + 1 : false_hit["file_offset"] + 5] == b"\x01\x00\x00\x00")
        results.append(patch.restore(patched, sites, image) == image.data)

        code = main({"sample": path, "table": None})
        results.append(code == cli.EXIT_OK)

    passed = sum(1 for item in results if item)
    sys.stdout.write("\nbool_stub_scan self test: {}/{} assertions passed\n".format(passed, len(results)))
    return cli.EXIT_OK if passed == len(results) else cli.EXIT_SELFTEST


if __name__ == "__main__":
    sys.exit(cli.run(main, self_test))
