#!/usr/bin/env node
/**
 * Generates server/hub.mjs (the installed service artifact) from
 *   server/hub.src.mjs          service source
 *   src/bridge/host-bridge.js   page-side bridge
 *   payload/manifest.json       pinned upstream archive + app identity
 *
 * The hub is a single file because `plugin.json#providers.services[…].runtime`
 * installs exactly the artifacts it lists: one file, one sha256.
 *
 *   node scripts/build-hub.mjs           write server/hub.mjs
 *   node scripts/build-hub.mjs --check   fail if it is stale
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFile, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");

const [source, bridge, pin] = await Promise.all([
  readFile(path.join(root, "server/hub.src.mjs"), "utf8"),
  readFile(path.join(root, "src/bridge/host-bridge.js"), "utf8"),
  readFile(path.join(root, "payload/manifest.json"), "utf8").then(JSON.parse),
]);

if (pin.schemaVersion !== 2) throw new Error("payload/manifest.json must be schemaVersion 2");
for (const key of ["version", "sha256", "sumsUrl", "localFile"]) {
  if (!pin[key]) throw new Error("payload/manifest.json is missing " + key);
}
if (!Array.isArray(pin.sources) || pin.sources.length === 0) {
  throw new Error("payload/manifest.json needs a non-empty sources[]");
}
for (const source of pin.sources) {
  if (!source || !source.id || !source.url) throw new Error("sources[] entries need id and url");
  // ADR 0008 D6: the shipped list is https only; the local http escape hatch is the
  // env override, which never lives in this file.
  if (!/^https:\/\//.test(source.url)) throw new Error("sources[] url must be https: " + source.url);
}
if (!/^[0-9a-f]{64}$/.test(pin.sha256)) throw new Error("payload/manifest.json sha256 must be 64 lowercase hex chars");

// The hub is shared by every craft plugin, so the app identity it renders with (name,
// seed, size label) travels in the pin instead of in the source.
if (!pin.app || typeof pin.app !== "object") throw new Error("payload/manifest.json needs an app block");
for (const key of ["id", "name", "envPrefix"]) {
  if (typeof pin.app[key] !== "string" || !pin.app[key]) throw new Error("payload/manifest.json app." + key + " is required");
}
if (pin.app.seedKey && (!pin.app.seedValue || typeof pin.app.seedValue !== "string")) {
  throw new Error("payload/manifest.json app.seedValue is required when app.seedKey is set");
}

const banner =
  "// GENERATED by scripts/build-hub.mjs from server/hub.src.mjs + src/bridge/host-bridge.js.\n" +
  "// Do not edit here: edit the sources and re-run `npm run build:hub`.\n";

const output =
  banner +
  source
    .replace("/* @inject:pin */ null", JSON.stringify(pin))
    .replace('/* @inject:bridge */ ""', JSON.stringify(bridge));

if (output.includes("/* @inject:")) throw new Error("an @inject marker was not replaced");

// `--check` compares bytes, so it would happily bless a stale file that does not
// parse. Parse the generated module once with the Node that will run it.
const probe = path.join(os.tmpdir(), "craft-hub-" + process.pid + ".mjs");
await writeFile(probe, output);
try {
  execFileSync(process.execPath, ["--check", probe], { stdio: "pipe" });
} catch (error) {
  throw new Error(
    "generated server/hub.mjs does not parse: " + String((error && error.stderr) || error),
  );
} finally {
  await rm(probe, { force: true });
}

const target = path.join(root, "server/hub.mjs");
const digest = createHash("sha256").update(output).digest("hex");

// plugin.json is what the host installs from: it lists the hub once per platform with
// its sha256, and a digest that no longer matches the file is a broken install for
// every one of them. Keeping the two in step by hand already went wrong once, so the
// generator owns both directions — write and check.
const manifestPath = path.join(root, "plugin.json");
const manifestText = await readFile(manifestPath, "utf8");
const pinned = new Set(manifestText.match(/[0-9a-f]{64}/g) ?? []);

if (check) {
	const current = await readFile(target, "utf8").catch(() => "");
	if (current !== output) {
		console.error("server/hub.mjs is stale — run `npm run build:hub`");
		process.exit(1);
	}
	const stale = [...pinned].filter((value) => value !== digest);
	if (stale.length > 0) {
		console.error("plugin.json pins a different hub sha256 — run `npm run build:hub`");
		process.exit(1);
	}
	console.log("server/hub.mjs is fresh · sha256 " + digest);
} else {
	await writeFile(target, output);
	if (pinned.size > 0) {
		let next = manifestText;
		for (const value of pinned) next = next.split(value).join(digest);
		if (next !== manifestText) await writeFile(manifestPath, next);
	}
	console.log("wrote server/hub.mjs · " + output.length + " B · sha256 " + digest);
}
