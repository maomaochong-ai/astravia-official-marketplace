#!/usr/bin/env node
/**
 * 把 agent/skills/<skill>/references、agent/references、agent/styles、agent/voice.md 打成纯数据模块，
 * 让工具在运行时直接返回工艺文档的原文，而不必在宿主里做文件 IO。
 *
 * 输出 src/reference/library.generated.ts 并提交进仓库：tsc 与 vitest 都直接吃它，
 * 构建期不需要额外步骤。改了 md 就重跑 `npm run references`。
 *
 * 技能目录拆分（ADR 0019）之后工艺文档分了两处；这里一次扫全，reference id 仍是文件名，
 * 所以工具与模型看到的名字没有变。`genres/<题材>/<文件>.md` 仍按 `<题材>-<文件>` 命名。
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const skillsDir = join(root, "agent", "skills");
const referencesDir = join(root, "agent", "references");
const stylesDir = join(root, "agent", "styles");
const voiceFile = join(root, "agent", "voice.md");
const output = join(root, "src", "reference", "library.generated.ts");

const skip = new Set(["ATTRIBUTION.md"]);

function titleOf(body, fallback) {
	const heading = body.match(/^#\s+(.+)$/m);
	return heading ? heading[1].trim() : fallback;
}

/** 目录里的 Markdown，按名字排序；缺目录返回空数组。 */
function markdownIn(dir) {
	let names;
	try {
		names = readdirSync(dir, { withFileTypes: true });
	} catch {
		return [];
	}
	return names
		.filter((entry) => entry.isFile() && entry.name.endsWith(".md") && !skip.has(entry.name))
		.sort((a, b) => a.name.localeCompare(b.name))
		.map((entry) => entry.name);
}

function subdirsIn(dir) {
	let names;
	try {
		names = readdirSync(dir, { withFileTypes: true });
	} catch {
		return [];
	}
	return names
		.filter((entry) => entry.isDirectory())
		.sort((a, b) => a.name.localeCompare(b.name))
		.map((entry) => entry.name);
}

/** @returns {{ id: string, kind: string, title: string, body: string }[]} */
function collect() {
	const entries = [];
	const push = (path, id, kind, title) => {
		const body = readFileSync(path, "utf8").trim();
		entries.push({ id, kind, title: title ?? titleOf(body, id), body });
	};

	// 1. 技能自带的参考：agent/skills/<skill>/references/**.md
	for (const skill of subdirsIn(skillsDir)) {
		const dir = join(skillsDir, skill, "references");
		for (const name of markdownIn(dir)) push(join(dir, name), name.replace(/\.md$/, ""), "guide");
		for (const genre of subdirsIn(join(dir, "genres"))) {
			for (const name of markdownIn(join(dir, "genres", genre))) {
				const slug = name.replace(/\.md$/, "");
				push(join(dir, "genres", genre, name), `${genre}-${slug}`, "genre", `${genre} ${slug}`);
			}
		}
	}

	// 2. 留在 agent/references 的只有署名与少数公共说明。
	for (const name of markdownIn(referencesDir)) push(join(referencesDir, name), name.replace(/\.md$/, ""), "guide");

	// 3. 风格档与叙述者。
	for (const name of markdownIn(stylesDir)) push(join(stylesDir, name), name.replace(/\.md$/, ""), "style");
	const voice = readFileSync(voiceFile, "utf8").trim();
	push(voiceFile, "voice", "voice", titleOf(voice, "voice"));

	return entries;
}

const entries = collect();
const seen = new Set();
for (const entry of entries) {
	if (seen.has(entry.id)) throw new Error(`Duplicate reference id: ${entry.id}`);
	seen.add(entry.id);
}

const total = entries.reduce((sum, entry) => sum + entry.body.length, 0);
const header = `// AUTO-GENERATED by scripts/build-reference-library.mjs — do not edit by hand.
// 源文件：agent/skills/*/references/**、agent/references/**、agent/styles/**、agent/voice.md。
// 改完跑 \`npm run references\`。
import type { BundledReference } from "./reference-types.js";

/** ${entries.length} 篇，共 ${total} 字符。 */
export const REFERENCE_LIBRARY: readonly BundledReference[] = [`;

const body = entries
	.map(
		(entry) =>
			`\t{\n\t\tid: ${JSON.stringify(entry.id)},\n\t\tkind: ${JSON.stringify(entry.kind)},\n\t\ttitle: ${JSON.stringify(
				entry.title,
			)},\n\t\tbody: ${JSON.stringify(entry.body)},\n\t},`,
	)
	.join("\n");

writeFileSync(output, `${header}\n${body}\n];\n`, "utf8");
process.stdout.write(`wrote ${relative(root, output)} — ${entries.length} entries, ${total} chars\n`);
