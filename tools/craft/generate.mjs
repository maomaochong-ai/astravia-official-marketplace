/* ------------------------------------------------------- payload + hub gate */

function payloadPin(app) {
  const { payload } = app;
  const tag = `v${payload.version}`;
  const base = `${app.repo}/releases/download/${tag}`;
  const name = `${app.id}-web-${payload.version}.zip`;
  return {
    schemaVersion: 2,
    archive: "zip",
    version: payload.version,
    size: payload.size,
    sha256: payload.sha256,
    sumsUrl: `${base}/SHA256SUMS.txt`,
    localFile: payload.localFile,
    sources: [
      { id: "upstream", url: `${base}/${name}` },
      { id: "ghproxy", url: `https://ghproxy.net/${base}/${name}` },
    ],
    upstream: app.repo,
    app: {
      id: app.id,
      name: app.name,
      envPrefix: app.id.toUpperCase().replace(/-/g, "_"),
      sizeLabel: payload.sizeLabel,
      // Whether this build can draw a Chinese interface at all: only then may the
      // hub replace navigator.languages (ADR craft/0003 D1).
      locale: app.locale ?? null,
      ...(app.seed ? { seedKey: app.seed.key, seedValue: app.seed.value } : {}),
    },
  };
}

/* ---------------------------------------------------------------- showcase */

function showcase(app, lang) {
  const { user, assistant } = app.detail[lang].showcase;
  const limits = lang === "zh" ? { user: 46, assistant: 58 } : { user: 90, assistant: 118 };
  const problems = [];
  if (renderedWidth(user) > limits.user) problems.push(`user_prompt ${renderedWidth(user)} > ${limits.user}`);
  if (renderedWidth(assistant) > limits.assistant) problems.push(`assistant_reply ${renderedWidth(assistant)} > ${limits.assistant}`);
  if (problems.length > 0) {
    throw new Error(`${app.id} (${lang}) showcase copy overflows the card: ${problems.join(", ")}`);
  }
  return {
    template: "chat-over-canvas",
    canvas: app.detail[lang].showcase.canvas,
    user_prompt: user,
    assistant_reply: assistant,
  };
}

function detailBlocks(app, lang) {
  const d = app.detail[lang];
  const titles =
    lang === "zh"
      ? { features: "你能得到什么", steps: "怎么开始", links: "出处" }
      : { features: "What it gives you", steps: "How to start", links: "Where it comes from" };
  // The tab shell speaks Chinese; the editor inside it may not. Say that here,
  // next to the other limits, instead of letting it be discovered after a 40 MB
  // download. Only apps whose upstream really has a Chinese UI skip the note.
  const languageNote =
    app.locale === "zh"
      ? null
      : lang === "zh"
        ? "界面语言：编辑器自身的界面只有英文（上游没有提供别的语言）。标签外壳、准备页与本页说明跟随 Astravia 的语言。"
        : "Interface language: the editor itself is English only — upstream ships no other language. The tab shell, the preparation page and this page follow your Astravia language.";
  return [
    { type: "hero", title: d.heroTitle, eyebrow: d.eyebrow, description: d.heroDescription, badges: d.badges },
    { type: "showcase", showcase: showcase(app, lang) },
    { type: "feature-grid", title: d.featuresTitle ?? titles.features, items: d.features },
    { type: "steps", title: d.stepsTitle ?? titles.steps, items: d.steps },
    ...d.callouts.map((callout) => ({ type: "callout", tone: callout.tone, content: callout.content })),
    ...(languageNote ? [{ type: "callout", tone: "info", content: languageNote }] : []),
    { type: "links", title: d.linksTitle ?? titles.links, items: d.links },
  ];
}

/* ------------------------------------------------------------------- skill */

function docSources(app) {
  const repo = join(CLONES, app.id);
  if (!existsSync(repo)) {
    console.warn(`  ! ${app.id}: upstream clone missing at ${repo}; publishing a skill with no references`);
    return [];
  }
  const base = join(repo, app.docs.path);
  if (!existsSync(base)) throw new Error(`${app.id}: docs path missing: ${base}`);

  // `AGENTS.md` / `CLAUDE.md` inside a docs tree are instructions for whoever works
  // on that repo — copying them into a skill would feed authoring rules to the host
  // as if they described the app.
  const wanted = (name) => name.endsWith(".md") && !/(^|\/)(AGENTS|CLAUDE)\.md$/.test(name);

  const files =
    app.docs.kind === "flat"
      ? readdirSync(base)
          .filter((name) => wanted(name) && statSync(join(base, name)).isFile())
          .map((name) => ({ from: join(base, name), to: name }))
      : walk(base)
          .filter(wanted)
          .map((name) => ({ from: join(base, name), to: name }));
    app.docs.kind === "flat"
      ? readdirSync(base)
          .filter((name) => name.endsWith(".md") && statSync(join(base, name)).isFile())
          .map((name) => ({ from: join(base, name), to: name }))
      : walk(base)
          .filter((name) => name.endsWith(".md"))
          .map((name) => ({ from: join(base, name), to: name }));

  return files.map((file) => {
    const heading = readFileSync(file.from, "utf8")
      .split("\n")
      .find((line) => line.startsWith("# "));
    return { ...file, title: heading ? heading.slice(2).trim() : file.to.replace(/\.md$/, "") };
  });
}

