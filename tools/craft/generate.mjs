#!/usr/bin/env node
/**
 * Render the craft plugins from `apps.mjs` + `stem/`.
 *
 * Why a generator instead of seven hand-maintained copies: the seven plugins are
 * the same program with a different payload pinned. Copying ~20 files seven times
 * means seven places for the bridge protocol to drift, and the first symptom
 * would be a published plugin whose hooks silently stopped matching. Here the
 * shared code is copied byte for byte, and the only per-app file in `src/` is
 * `app.config.ts` — so a bug can only be app-specific if it is in that file.
 *
 * Everything is written, never merged: re-running it is safe and produces the
 * same bytes.
 *
 *   node tools/craft/generate.mjs             # write all seven
 *   node tools/craft/generate.mjs designcraft # write one
 */

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { APPS } from "./apps.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "../..");
const STEM = join(HERE, "stem");
const CLONES = resolve(ROOT, "../craft/code-clone");
const ZIP_CACHE = "/tmp/craft-zips";

/** Same five platform keys, same shape, as the plugin published before this generator. */
const PLATFORMS = ["win32-x64", "darwin-x64", "darwin-arm64", "linux-x64", "linux-arm64"];

const CATEGORY_ZH = { Design: "设计", Media: "媒体", Documents: "文档" };

const selected = process.argv.slice(2);
const apps = selected.length > 0 ? APPS.filter((app) => selected.includes(app.id)) : APPS;

if (apps.length === 0) {
  console.error(`no such app; known: ${APPS.map((a) => a.id).join(", ")}`);
  process.exit(1);
}

/* ------------------------------------------------------------------ helpers */

const sha256 = (buf) => createHash("sha256").update(buf).digest("hex");

function write(path, contents) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, contents);
}

function json(path, value) {
  write(path, `${JSON.stringify(value, null, 2)}\n`);
}

/** Every file under `dir`, relative to it, sorted so output is stable. */
function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      for (const child of walk(full)) out.push(join(name, child));
    } else {
      out.push(name);
    }
  }
  return out;
}

const countCjk = (text) => (text.match(/[\u3400-\u9fff\uff00-\uffef]/g) ?? []).length;

/**
 * The capability page renders the showcase inside a fixed-height rounded card.
 * Copy that runs long is not wrapped there — it is clipped by the container,
 * which is the defect this generator has to prevent. Width is what matters, and
 * a CJK glyph takes roughly twice the horizontal room of a Latin one.
 */
const renderedWidth = (text) => countCjk(text) + (text.length - countCjk(text));

